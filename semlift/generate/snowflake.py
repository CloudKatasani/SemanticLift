"""Snowflake generator: one object per file, dependency ordered, byte-deterministic (spec 7.1)."""
from __future__ import annotations

import re

from .. import __version__
from ..design.model import Design, TableDesign
from ..design.naming import constants_table
from ..model import MetaGraph, TargetObject
from ..util import sql_str

LAYER_BASE = {"setup": 0, "ref": 1000, "secmap": 1500, "secpol": 1600, "core": 2000, "agg": 4000, "sem": 5000,
              "dp": 6000, "grants": 7000}
LAYER_DIR = {"setup": "setup", "ref": "ref", "secmap": "sec", "secpol": "sec", "core": "core", "agg": "agg",
             "sem": "sem", "dp": "dp", "grants": "sec"}


def header(obj_id: str, kind: str, rules: list[str], conf: float, status: str, evidence: list[str],
           owner: str = "", cls: str = "") -> str:
    lines = [
        "-- " + "=" * 74,
        f"-- Object      : {obj_id} ({kind})",
        f"-- Generated by: SemanticLift {__version__}",
        f"-- Rules       : {', '.join(sorted(set(rules))) or '-'}",
        f"-- Confidence  : {conf:.2f} ({status})",
    ]
    if owner or cls:
        lines.append(f"-- Governance  : owner={owner}; classification={cls}")
    for e in evidence[:6]:
        lines.append(f"-- Evidence    : {e}")
    if status == "stub":
        lines.append("-- STUB        : inferred object below auto-approve threshold; never auto-deployed.")
        lines.append("--               Resolve TODO source mappings and obtain steward approval first.")
    lines.append("-- " + "=" * 74)
    return "\n".join(lines) + "\n"


def tag_clause(tag_schema: str, tags: dict[str, str]) -> str:
    if not tags:
        return ""
    return "WITH TAG (" + ", ".join(f"{tag_schema}.{k} = {sql_str(v)}" for k, v in sorted(tags.items())) + ")"


class SnowflakeGenerator:
    def __init__(self, g: MetaGraph, d: Design, cfg: dict):
        self.g, self.d, self.cfg = g, d, cfg
        self.ts = cfg["target"]["tag_schema"]
        self.db = cfg["target"]["database"]
        self.objects: list[TargetObject] = []
        self.counters = {k: 0 for k in LAYER_BASE}

    def add(self, layer: str, oid: str, otype: str, ddl: str, *, comment="", owner="", cls="", domain="",
            product="", conf=1.0, stub=False, rules=None, lineage=None, deps=None, cognos="", meta=None) -> TargetObject:
        self.counters[layer] += 10
        order = LAYER_BASE[layer] + self.counters[layer]
        schema, _, name = oid.partition(".")
        stub = stub or conf < self.cfg["confidence"]["auto_approve_min"]
        status = "stub" if stub else "proposed"
        text = header(oid, otype, rules or [], conf, status, lineage or [], owner, cls) + ddl.rstrip() + "\n"
        t = TargetObject(id=oid, layer=LAYER_DIR[layer], object_type=otype, schema=schema, name=name or schema,
                         ddl=text, comment=comment, owner=owner, classification=cls, domain=domain, product=product,
                         confidence=round(conf, 2), status=status, rule_ids=sorted(set(rules or [])),
                         lineage=lineage or [], depends_on=deps or [], order=order, cognos_source=cognos,
                         meta=dict(meta or {}))
        safe = re.sub(r"[^A-Za-z0-9_]+", "_", oid.replace(".", "__"))
        t.meta["file"] = f"ddl/{LAYER_DIR[layer]}/{order:04d}_{safe}.sql"
        self.objects.append(t)
        return t

    # ------------------------------------------------------------ setup
    def setup(self) -> None:
        d, cfg = self.d, self.cfg
        schemas = ["CORE", "REF", "AGG", "SEM", "SEC"] + ([self.ts] if self.ts not in ("CORE", "REF", "AGG", "SEM", "SEC") else []) \
            + sorted({p.schema for p in d.products.values()})
        ddl = "\n".join(f"CREATE SCHEMA IF NOT EXISTS {s}\n  COMMENT = {sql_str(f'SemanticLift {s} layer')};" for s in schemas)
        self.add("setup", "SETUP.SCHEMAS", "schema", ddl, comment="Target schemas", rules=["NAME-01"],
                 owner=self._own(), cls="Internal")
        roles = set()
        for r in self.g.security_rules.values():
            roles.update(r.roles_in + r.roles_exempt + r.roles_denied)
        for ab in self.g.security_rules.values():
            if ab.type == "abac":
                roles.update(re.findall(r"'([A-Za-z_]+)'", ab.predicate) if "role" in ab.predicate else [])
        from ..design.security import sf_role
        roles_sf = sorted({sf_role(cfg, r) for r in roles} - {"PUBLIC"})
        ddl = "\n".join(f"CREATE ROLE IF NOT EXISTS {r} COMMENT = 'Mapped from Cognos role';" for r in roles_sf)
        self.add("setup", "SETUP.ROLES", "role", ddl, comment="Roles mapped from Cognos security", rules=["SEC-00"],
                 owner=self._own(), cls="Internal")
        ddl = "\n".join(f"CREATE TAG IF NOT EXISTS {self.ts}.{t}\n  COMMENT = 'SemanticLift governance tag';" for t in d.tags)
        self.add("setup", "SETUP.TAGS", "tag", ddl, comment="Governance tags", rules=["CORE-09"],
                 owner=self._own(), cls="Internal", deps=["SETUP.SCHEMAS"])

    def _own(self) -> str:
        from ..design.core import owner
        return owner(self.g, self.cfg)

    def _cls(self) -> str:
        from ..design.core import classification
        return classification(self.g)

    # ------------------------------------------------------------ ref
    def ref(self) -> None:
        g = self.g
        params = sorted(g.parameters.values(), key=lambda p: p.name)
        rows = ",\n    ".join(
            f"({sql_str(p.name)}, {sql_str(p.data_type)}, {sql_str(p.default) if p.default is not None else 'NULL'}, "
            f"{'TRUE' if p.required else 'FALSE'}, {'TRUE' if p.multi_select else 'FALSE'}, "
            f"{sql_str(p.validation) if p.validation else 'NULL'}, {sql_str(p.prompt_text) if p.prompt_text else 'NULL'})"
            for p in params)
        ddl = ("CREATE OR ALTER TABLE REF.PARAM_DEFINITION (\n    PARAMETER_NAME VARCHAR NOT NULL,\n    DATA_TYPE VARCHAR,\n"
               "    DEFAULT_VALUE VARCHAR,\n    IS_REQUIRED BOOLEAN,\n    IS_MULTI_SELECT BOOLEAN,\n    VALIDATION_RULE VARCHAR,\n"
               "    PROMPT_TEXT VARCHAR,\n    CONSTRAINT PK_PARAM_DEFINITION PRIMARY KEY (PARAMETER_NAME)\n)\n"
               "COMMENT = 'Cognos prompt definitions (parameter maps); documented filter dimensions for consumers';\n\n"
               f"INSERT OVERWRITE INTO REF.PARAM_DEFINITION VALUES\n    {rows};")
        self.add("ref", "REF.PARAM_DEFINITION", "table", ddl, comment="Parameter definitions", rules=["REF-01"],
                 owner=self._own(), cls="Internal", domain="ENTERPRISE", product="ENTERPRISE",
                 lineage=sorted({f"{p.prov.source_file}" for p in params if p.prov}), deps=["SETUP.SCHEMAS"])
        from ..util import snake_upper
        for p in params:
            if not p.pick_list:
                continue
            tname = f"REF.PARAM_{snake_upper(p.name[2:] if p.name.startswith('p_') else p.name)}"
            vals = ",\n    ".join(f"({sql_str(i['value'])}, {sql_str(i['label'] or i['value'])}, {n + 1}, "
                                  f"{'TRUE' if str(p.default) == str(i['value']) else 'FALSE'})"
                                  for n, i in enumerate(p.pick_list))
            ddl = (f"CREATE OR ALTER TABLE {tname} (\n    VALUE VARCHAR NOT NULL,\n    LABEL VARCHAR,\n    SORT_ORDER NUMBER(38,0),\n"
                   f"    IS_DEFAULT BOOLEAN,\n    CONSTRAINT PK_{tname.split('.')[1]} PRIMARY KEY (VALUE)\n)\n"
                   f"COMMENT = {sql_str(f'Pick list for Cognos prompt ?{p.name}? ({p.prompt_text or p.name})')};\n\n"
                   f"INSERT OVERWRITE INTO {tname} VALUES\n    {vals};")
            self.add("ref", tname, "table", ddl, comment=f"Reference values for {p.name}", rules=["REF-01"],
                     owner=self._own(), cls="Internal", domain="ENTERPRISE", product="ENTERPRISE",
                     lineage=[f"{p.prov.source_file}:{p.prov.locator}"] if p.prov else [], deps=["SETUP.SCHEMAS"],
                     cognos=f"?{p.name}? pick list: {[i['value'] for i in p.pick_list]}")
        if self.d.constants:
            rows = ",\n    ".join(f"({sql_str(c['code'])}, {c['value']}, {sql_str(c['unit'])}, '1900-01-01'::DATE, NULL, "
                                   f"{sql_str(c['description'])}, {sql_str(c['entity'] + '.' + c['item'])})" for c in self.d.constants)
            ct = constants_table(self.cfg)
            ddl = (f"CREATE OR ALTER TABLE {ct} (\n    FACTOR_CODE VARCHAR NOT NULL,\n    FACTOR_VALUE NUMBER(18,6) NOT NULL,\n"
                   "    UNIT VARCHAR,\n    EFFECTIVE_FROM DATE NOT NULL,\n    EFFECTIVE_TO DATE,\n    DESCRIPTION VARCHAR,\n"
                   f"    COGNOS_SOURCE VARCHAR,\n    CONSTRAINT PK_{ct.split('.')[1]} PRIMARY KEY (FACTOR_CODE, EFFECTIVE_FROM)\n)\n"
                   "COMMENT = 'Governed, effective-dated constants externalized from FM calculations (finding F12)';\n\n"
                   "-- Seed with the value hard-coded in Cognos; stewards add new effective-dated rows going forward.\n"
                   f"MERGE INTO {ct} t USING (SELECT * FROM VALUES\n    " + rows +
                   "\n) s (FACTOR_CODE, FACTOR_VALUE, UNIT, EFFECTIVE_FROM, EFFECTIVE_TO, DESCRIPTION, COGNOS_SOURCE)\n"
                   "ON t.FACTOR_CODE = s.FACTOR_CODE AND t.EFFECTIVE_FROM = s.EFFECTIVE_FROM\n"
                   "WHEN NOT MATCHED THEN INSERT VALUES (s.FACTOR_CODE, s.FACTOR_VALUE, s.UNIT, s.EFFECTIVE_FROM, s.EFFECTIVE_TO, s.DESCRIPTION, s.COGNOS_SOURCE);")
            self.add("ref", ct, "table", ddl, comment="Externalized constants", rules=["CORE-05"],
                     owner=self._own(), cls="Internal", domain="ENTERPRISE", product="ENTERPRISE", deps=["SETUP.SCHEMAS"],
                     cognos="; ".join(f"{c['entity']}.{c['item']} literal {c['value']}" for c in self.d.constants))

    # ------------------------------------------------------------ security
    def sec(self) -> None:
        d = self.d
        for sid, s in sorted(d.sec_tables.items()):
            if s["kind"] == "user_map":
                cols = ", ".join(["USERNAME"] + s["columns"])
                todo = "" if s["known"] else (f"-- TODO: {s['source']} is not in the data source inventory (.ds); "
                                              "confirm the landed table before deployment\n")
                ddl = (todo + f"CREATE OR REPLACE VIEW {sid}\n  COMMENT = {sql_str('User entitlement mapping for ' + ', '.join(s['rules']) + '. USERNAME must match CURRENT_USER().')}\n"
                       f"AS\nSELECT UPPER(USERNAME) AS USERNAME, {', '.join(s['columns'])}\nFROM {s['source']};")
                self.add("secmap", sid, "view", ddl, comment="Entitlement mapping", rules=["SEC-01"], owner=self._own(),
                         cls="Restricted", conf=1.0 if s["known"] else 0.6, lineage=[s["source"]], deps=["SETUP.SCHEMAS"],
                         cognos="; ".join(s["rules"]))
            elif s["kind"] == "role_grant":
                rows = ",\n    ".join(f"({sql_str(a)}, {sql_str(r)}, {sql_str(t)}, {sql_str(src)})" for a, r, t, src in s["rows"])
                ddl = ("CREATE OR ALTER TABLE SEC.MAP_ROLE_GRANT (\n    ACCESS_GROUP VARCHAR NOT NULL,\n    ROLE_NAME VARCHAR NOT NULL,\n"
                       "    GRANT_TYPE VARCHAR NOT NULL,\n    COGNOS_RULE VARCHAR\n)\n"
                       "COMMENT = 'Column grants from Cognos objectLevelSecurity, keyed by the ACCESS_GROUP tag';\n\n"
                       + (f"INSERT OVERWRITE INTO SEC.MAP_ROLE_GRANT VALUES\n    {rows};" if rows else ""))
                self.add("secmap", sid, "table", ddl, comment="Column grant mapping", rules=["SEC-03"], owner=self._own(),
                         cls="Restricted", deps=["SETUP.SCHEMAS"], cognos="; ".join(sorted({r[3] for r in s["rows"]})))
            elif s["kind"] == "user_attribute":
                ddl = ("CREATE OR ALTER TABLE SEC.MAP_USER_ATTRIBUTE (\n    USERNAME VARCHAR NOT NULL,\n    ATTRIBUTE_NAME VARCHAR NOT NULL,\n"
                       "    ATTRIBUTE_VALUE VARCHAR\n)\nCOMMENT = 'User attributes for ABAC conditions (e.g. dataClassification); load from the IdP';")
                self.add("secmap", sid, "table", ddl, comment="ABAC user attributes", rules=["SEC-04"], owner=self._own(),
                         cls="Restricted", deps=["SETUP.SCHEMAS"])
        for pid, p in sorted(d.policies.items(), key=lambda x: (x[1].kind, x[0])):
            sig = ", ".join(f"{a} {t}" for a, t in p.signature)
            kw = "ROW ACCESS POLICY" if p.kind == "row_access" else "MASKING POLICY"
            default = "TRUE" if p.kind == "row_access" else p.signature[0][0]
            ddl = (f"CREATE {kw} IF NOT EXISTS {pid} AS ({sig}) RETURNS {p.returns} -> {default}\n"
                   f"  COMMENT = {sql_str(p.comment)};\n\n"
                   f"ALTER {kw} {pid} SET BODY ->\n    {p.body};\n\n"
                   f"ALTER {kw} {pid} SET COMMENT = {sql_str(p.comment)};")
            att = "; ".join(f"{a['table']}({', '.join(a['columns'])})" for a in p.attachments) or "pending"
            self.add("secpol", pid, p.kind.replace("_", " ") + " policy", ddl, comment=p.comment, rules=["SEC-02" if p.kind == "row_access" else "SEC-03"],
                     owner=self._own(), cls="Restricted", conf=p.confidence, deps=["SETUP.TAGS"] + p.depends_on,
                     cognos=f"{p.cognos_rule}: {p.cognos_source}", meta={"attached_to": att})

    # ------------------------------------------------------------ core
    def core_view(self, t: TableDesign) -> str:
        cols = []
        sel = []
        for c in t.columns:
            parts = [f"    {c.name}"]
            if c.masking_policy:
                parts.append(f"WITH MASKING POLICY {c.masking_policy}")
            if c.tags:
                parts.append(tag_clause(self.ts, c.tags))
            comment = c.comment + (" [TODO: unconfirmed source]" if c.todo and "TODO" not in c.comment else "")
            parts.append(f"COMMENT {sql_str(comment)}")
            cols.append(" ".join(parts))
            sel.append(f"    {c.expr:<45} AS {c.name}" + ("  /* TODO */" if c.todo else ""))
        head = f"CREATE OR REPLACE VIEW {t.id} (\n" + ",\n".join(cols) + "\n)"
        if t.row_access_policy:
            head += f"\n  WITH ROW ACCESS POLICY {t.row_access_policy[0]} ON ({', '.join(t.row_access_policy[1])})"
        head += f"\n  {tag_clause(self.ts, t.tags)}\n  COMMENT = {sql_str(t.comment)}\nAS\n"
        if t.union_sources:
            key_cols = [c for c in t.columns if c.kind == "key"]
            parts = []
            for us in t.union_sources:
                src, col = us.split("|")
                parts.append(f"-- TODO: replace with master table\nSELECT src.{col} AS {key_cols[0].name}\nFROM {src} src")
            return head + "\nUNION\n".join(parts) + ";"
        body = ("SELECT DISTINCT\n" if t.distinct else "SELECT\n") + ",\n".join(sel)
        if t.stub:
            body += "\n-- TODO: confirm landed source table"
        body += f"\nFROM {t.source} {t.source_alias}"
        for j in t.joins:
            body += (f"\n-- {j.comment}" if j.comment else "") + f"\n{j.kind} {j.table} {j.alias}\n    ON {j.on}"
        return head + body + ";"

    def core(self) -> None:
        d = self.d
        order = sorted(d.tables.values(), key=lambda t: (t.kind != "dimension", t.id))
        for t in order:
            deps = ["SETUP.TAGS"]
            if t.row_access_policy:
                deps.append(t.row_access_policy[0])
            deps += sorted({c.masking_policy for c in t.columns if c.masking_policy})
            if any(j.table.startswith("REF.") for j in t.joins):
                deps += sorted({j.table for j in t.joins if j.table.startswith("REF.")})
            fks = "\n".join(
                f"-- RELY constraint (documentation + join elimination): {t.id}({', '.join(fk.columns)}) -> {fk.ref_table}({', '.join(fk.ref_columns)})"
                for fk in t.foreign_keys)
            ddl = self.core_view(t)
            if fks:
                ddl += "\n\n" + fks
            cognos = "\n".join(t.cognos_source)
            self.add("core", t.id, "view", ddl, comment=t.comment, owner=t.tags.get("DATA_OWNER", ""),
                     cls=t.tags.get("DATA_CLASSIFICATION", ""), domain=t.domain, product=t.domain, conf=t.confidence,
                     stub=t.stub, rules=t.rule_ids, lineage=t.evidence + [t.source], deps=deps, cognos=cognos,
                     meta={"kind": t.kind, "entity": t.entity, "columns": len(t.columns),
                           "todo_columns": sum(1 for c in t.columns if c.todo)})

    # ------------------------------------------------------------ agg
    def agg(self) -> None:
        d = self.d
        for aid, a in sorted(d.aggregates.items()):
            ft = d.tables[a.fact_table]
            sel = [f"{al}.{col} AS {out}" if col != out else f"{al}.{col}" for al, col, out in a.group_columns]
            sel += [f"{sql} AS {out}" for out, sql, _k in a.measures]
            frm = f"FROM {a.fact_table} f\n" + "".join(f"JOIN {tid} {al} ON {on}\n" for al, tid, on in a.joins)
            body = "SELECT " + ",\n       ".join(sel) + "\n" + frm + "GROUP BY ALL"
            comment = (f"Demand-driven aggregate of {ft.name} at grain {', '.join(a.grain_refs)}; covers {a.coverage_pct}% of "
                       f"weighted demand ({len(a.clusters)} clusters); est. {a.est_rows:,} rows; ~{a.credits_per_day} credits/day")
            if a.implementation == "dynamic_table":
                ddl = (f"CREATE OR REPLACE DYNAMIC TABLE {aid}\n  TARGET_LAG = {sql_str(a.target_lag)}\n  WAREHOUSE  = {a.warehouse}\n"
                       f"  COMMENT = {sql_str(comment)}\nAS\n{body};")
                post = []
                for out, _sql, kind in a.measures:
                    c = ft.col(out)
                    if c is not None and c.masking_policy:
                        post.append(f"ALTER DYNAMIC TABLE {aid} MODIFY COLUMN {out} SET MASKING POLICY {c.masking_policy};")
                        for k, v in sorted(c.tags.items()):
                            post.append(f"ALTER DYNAMIC TABLE {aid} MODIFY COLUMN {out} SET TAG {self.ts}.{k} = {sql_str(v)};")
                for al, col, out in a.group_columns:
                    tid = next(t for x, t, _ in a.joins if x == al) if al != "f" else a.fact_table
                    t = d.tables[tid]
                    if t.row_access_policy and t.row_access_policy[1] == [col]:
                        post.append(f"ALTER DYNAMIC TABLE {aid} ADD ROW ACCESS POLICY {t.row_access_policy[0]} ON ({out});")
                if post:
                    ddl += ("\n\n-- Dynamic tables refresh with the owner's privileges: re-apply source policies on the aggregate.\n"
                            + "\n".join(post))
            elif a.implementation == "materialized_view":
                ddl = f"CREATE OR REPLACE MATERIALIZED VIEW {aid}\n  COMMENT = {sql_str(comment)}\nAS\n{body};"
            else:
                ddl = f"CREATE OR REPLACE VIEW {aid}\n  COMMENT = {sql_str(comment)}\nAS\n{body};"
            if a.excluded:
                ddl += "\n\n-- Excluded grain attributes (fan trap / no n:1 path): " + ", ".join(a.excluded)
            deps = [a.fact_table] + [tid for _, tid, _ in a.joins]
            self.add("agg", aid, a.implementation.replace("_", " "), ddl, comment=comment, owner=ft.tags.get("DATA_OWNER", ""),
                     cls=ft.tags.get("DATA_CLASSIFICATION", ""), domain=a.domain, product=a.domain, conf=a.confidence,
                     stub=a.stub, rules=["AGG-01", "AGG-02", "AGG-04"] + (["AGG-03"] if "Date.MonthNumber" in a.grain_refs else []),
                     lineage=[f"clusters: {', '.join(a.clusters)}"], deps=deps,
                     meta={"coverage_pct": a.coverage_pct, "credits_per_day": a.credits_per_day, "est_rows": a.est_rows})

    # ------------------------------------------------------------ sem
    def sem(self) -> None:
        d = self.d
        for sid, sv in sorted(d.semantic_views.items()):
            def syn(lst):
                lst = [s for s in lst if s]
                return f" WITH SYNONYMS ({', '.join(sql_str(s) for s in lst)})" if lst else ""
            tables = ",\n".join(f"    {t.alias:<14} AS {t.table} PRIMARY KEY ({', '.join(t.primary_key)}){syn(t.synonyms)}"
                                f"\n      COMMENT = {sql_str(t.comment)}" for t in sv.tables)
            rels = ",\n".join(f"    {r.name} AS {r.from_alias} ({', '.join(r.from_columns)}) REFERENCES {r.to_alias}"
                              + (f" ({', '.join(r.to_columns)})" if r.to_columns else "") for r in sv.relationships)
            facts = ",\n".join(f"    {f.alias}.{f.name} AS {f.expr}\n      COMMENT = {sql_str(f.comment)}" for f in sv.facts)
            dims = ",\n".join(f"    {f.alias}.{f.name} AS {f.expr}{syn(f.synonyms)}\n      COMMENT = {sql_str(f.comment)}" for f in sv.dimensions)
            mets = ",\n".join(f"    {f.alias}.{f.name} AS {f.expr}{syn(f.synonyms)}\n      COMMENT = {sql_str(f.comment)}" for f in sv.metrics)
            parts = [f"CREATE OR REPLACE SEMANTIC VIEW {sid}", f"  TABLES (\n{tables}\n  )"]
            if rels:
                parts.append(f"  RELATIONSHIPS (\n{rels}\n  )")
            if facts:
                parts.append(f"  FACTS (\n{facts}\n  )")
            if dims:
                parts.append(f"  DIMENSIONS (\n{dims}\n  )")
            if mets:
                parts.append(f"  METRICS (\n{mets}\n  )")
            pk = sorted({self.g.reports[c].package for cl in sv.clusters for c in [self.g.clusters[cl].canonical]})
            parts.append(f"  COMMENT = {sql_str(f'{sv.description}. Generated by SemanticLift from ' + (', '.join(pk) or sv.domain) + '; FM default aggregations enforced')}")
            ddl = "\n".join(parts) + ";"
            if sv.default_filters:
                ddl += "\n\n-- Consumer contract default filters (required Cognos prompts): " + "; ".join(
                    f"{f['dimension']} = {f['default']} (?{f['parameter']}?)" for f in sv.default_filters)
            pres_roles = sorted({role for r in self.d.sec_tables.get("SEC.GRANTS", {}).get("rows", [])
                                 if r["kind"] == "presentation" for role in r["allow"]})
            if pres_roles:
                ddl += "\n\n" + "\n".join(f"GRANT REFERENCES, SELECT ON SEMANTIC VIEW {sid} TO ROLE {role};" for role in pres_roles)
            deps = [t.table for t in sv.tables]
            self.add("sem", sid, "semantic view", ddl, comment=sv.description, owner=self._own(), cls=self._cls(),
                     domain=sv.domain, product=sv.domain, conf=sv.confidence, stub=sv.stub,
                     rules=["SEM-01", "SEM-02", "SEM-03"], lineage=[f"clusters: {', '.join(sv.clusters[:20])}"], deps=deps,
                     meta={"tables": len(sv.tables), "dimensions": len(sv.dimensions), "metrics": len(sv.metrics),
                           "verified_queries": len(sv.verified_queries)})

    # ------------------------------------------------------------ dp
    def dp(self) -> None:
        d = self.d
        for oid, o in sorted(d.outputs.items()):
            ddl = (f"CREATE OR REPLACE SECURE VIEW {oid}\n  {tag_clause(self.ts, {'DOMAIN': o.product, 'DATA_OWNER': self._own(), 'DATA_CLASSIFICATION': self._cls()})}\n"
                   f"  COMMENT = {sql_str(o.comment)}\nAS\n{o.sql};")
            self.add("dp", oid, "secure view", ddl, comment=o.comment, owner=self._own(), cls=self._cls(), domain=o.product,
                     product=o.product, conf=o.confidence, stub=o.stub, rules=["DP-01"], deps=o.depends_on)
        for key, p in sorted(d.products.items()):
            share = f"{p.schema}_SHARE"
            outs = [o for o in p.outputs if not d.outputs[o].stub]
            pconf = min([d.outputs[o].confidence for o in outs] or [p.confidence])
            grants = "\n".join(f"GRANT SELECT ON VIEW {self.db}.{o} TO SHARE {share};" for o in outs)
            manifest = (f"title: {sql_str(p.name)[1:-1]!r}\nsubtitle: 'SemanticLift data product ({p.slug})'\n"
                        f"description: |\n  {p.name} data product generated from Cognos package {key}.\n"
                        f"  Semantic views: {', '.join(p.semantic_views) or 'n/a'}. Contract: contracts/{p.slug}.yaml\n"
                        f"organization_profile: INTERNAL\norganization_targets:\n  access:\n    - all_internal_accounts: true\n"
                        f"locations:\n  access_regions:\n    - name: ALL\nsupport_contact: {sql_str(p.steward)[1:-1]!r}\n"
                        f"approver_contact: {sql_str(p.steward)[1:-1]!r}\n")
            ddl = (f"CREATE SHARE IF NOT EXISTS {share}\n  COMMENT = {sql_str('Share for data product ' + p.name)};\n"
                   f"GRANT USAGE ON DATABASE {self.db} TO SHARE {share};\nGRANT USAGE ON SCHEMA {self.db}.{p.schema} TO SHARE {share};\n"
                   + (grants + "\n" if grants else "-- No deployable outputs yet (all stubs)\n")
                   + f"\nCREATE ORGANIZATION LISTING IF NOT EXISTS {p.schema}_LISTING\n  SHARE {share} AS\n$$\n{manifest}$$\n  PUBLISH = FALSE;")
            self.add("dp", f"{p.schema}.LISTING", "share + internal listing", ddl, comment=f"Internal marketplace listing for {p.name}",
                     owner=p.owner, cls=p.classification, domain=key, product=key, conf=pconf,
                     stub=not outs, rules=["DP-02"], deps=outs)

    def grants(self) -> None:
        rows = self.d.sec_tables.get("SEC.GRANTS", {}).get("rows", [])
        lines = []
        for r in rows:
            lines.append(f"-- Cognos namespace visibility: {r['rule']} ({r['kind']})")
            for role in r["allow"]:
                for s in r["schemas"]:
                    lines.append(f"GRANT USAGE ON SCHEMA {s} TO ROLE {role};")
                    if r["kind"] == "presentation" and s == "SEM":
                        lines.append(f"-- semantic view grants to {role} are issued with each SEM object")
                    else:
                        lines.append(f"GRANT SELECT ON ALL VIEWS IN SCHEMA {s} TO ROLE {role};")
                        lines.append(f"GRANT SELECT ON FUTURE VIEWS IN SCHEMA {s} TO ROLE {role};")
            for role in r["deny"]:
                lines.append(f"-- Cognos denies {role}: no grant issued; verify {role} inherits no privileges on {', '.join(r['schemas'])}")
            lines.append("")
        if lines:
            self.add("grants", "SEC.GRANTS", "grants", "\n".join(lines), comment="Schema grants from namespace visibility",
                     owner=self._own(), cls="Restricted", rules=["SEC-05"], deps=["SETUP.SCHEMAS", "SETUP.ROLES"])

    def generate(self) -> list[TargetObject]:
        self.setup()
        self.ref()
        self.sec()
        self.core()
        self.agg()
        self.sem()
        self.dp()
        self.grants()
        return self.objects
