class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def to_yaml(obj) -> str:
    return yaml.dump(obj, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


SF_TO_CORTEX = {"VARCHAR": "VARCHAR", "BOOLEAN": "BOOLEAN", "DATE": "DATE", "TIMESTAMP_NTZ": "TIMESTAMP"}


def cortex_type(t: str) -> str:
    t = t.upper()
    if t.startswith("NUMBER"):
        return "NUMBER"
    return SF_TO_CORTEX.get(t, t)


# --------------------------------------------------------------------------- semantic YAML
def semantic_yaml(g: MetaGraph, d: Design, cfg: dict) -> dict[str, str]:
    """Snowflake Cortex Analyst semantic model YAML, one file per semantic view."""
    out = {}
    db = cfg["target"]["database"]
    for sid, sv in sorted(d.semantic_views.items()):
        tables = []
        for t in sv.tables:
            schema, name = t.table.split(".")
            td = d.tables[t.table]
            entry = {"name": t.alias, "description": t.comment,
                     "base_table": {"database": db, "schema": schema, "table": name},
                     "primary_key": {"columns": list(t.primary_key)}, "synonyms": t.synonyms}
            dims, tdims, facts, metrics = [], [], [], []
            for f in sv.dimensions:
                if f.alias != t.alias:
                    continue
                col = td.col(f.expr)
                item = {"name": f.name, "expr": f.expr, "data_type": cortex_type(f.data_type or (col.data_type if col else "VARCHAR")),
                        "description": f.comment}
                if f.synonyms:
                    item["synonyms"] = f.synonyms
                if f.sample_values:
                    item["sample_values"] = f.sample_values
                (tdims if cortex_type(item["data_type"]) in ("DATE", "TIMESTAMP") else dims).append(item)
            for f in sv.facts:
                if f.alias == t.alias:
                    facts.append({"name": f.name, "expr": f.expr, "data_type": cortex_type(f.data_type or "NUMBER"),
                                  "description": f.comment, **({"synonyms": f.synonyms} if f.synonyms else {})})
            for m in sv.metrics:
                if m.alias == t.alias:
                    metrics.append({"name": m.name, "expr": m.expr.replace(f"{m.alias}.", ""), "description": m.comment,
                                    **({"synonyms": m.synonyms} if m.synonyms else {})})
            for k, v in (("dimensions", dims), ("time_dimensions", tdims), ("facts", facts), ("metrics", metrics)):
                if v:
                    entry[k] = v
            tables.append(entry)
        doc = {
            "name": sv.name, "description": sv.description + f" (generated by SemanticLift {__version__})",
            "tables": tables,
            "relationships": [{"name": r.name, "left_table": r.from_alias, "right_table": r.to_alias,
                               "relationship_columns": [{"left_column": a, "right_column": b}
                                                        for a, b in zip(r.from_columns, r.to_columns)],
                               "join_type": "left_outer", "relationship_type": "many_to_one"} for r in sv.relationships],
            "verified_queries": [{"name": q.name, "question": q.question, "sql": q.sql, "verified_by": "SemanticLift (suggested)",
                                  "use_as_onboarding_question": i < 3} for i, q in enumerate(sv.verified_queries)],
        }
        if sv.default_filters:
            doc["custom_instructions"] = "Unless the user specifies otherwise, apply default filters: " + "; ".join(
                f"{f['dimension']} = {f['default']}" for f in sv.default_filters)
        out[f"semantic/snowflake/{sv.name}.yaml"] = to_yaml(doc)
    return out


# --------------------------------------------------------------------------- Databricks metric views
def databricks_metric_views(g: MetaGraph, d: Design, cfg: dict) -> dict[str, str]:
    out = {}
    catalog = cfg["target"]["database"].lower()
    for sid, sv in sorted(d.semantic_views.items()):
        fact_aliases = [t.alias for t in sv.tables if d.tables[t.table].kind == "fact"] or [sv.tables[0].alias]
        base = fact_aliases[0]
        base_t = next(t for t in sv.tables if t.alias == base)
        alias_table = {t.alias: t.table for t in sv.tables}
        joins = []
        reachable = {base}
        for r in sv.relationships:
            if r.from_alias in reachable or r.from_alias == base:
                src = "source" if r.from_alias == base else r.from_alias
                joins.append({"name": r.to_alias, "source": f"{catalog}.{alias_table[r.to_alias].lower()}",
                              "on": " AND ".join(f"{src}.{a} = {r.to_alias}.{b}" for a, b in zip(r.from_columns, r.to_columns))})
                reachable.add(r.to_alias)
        prefix = lambda a: "" if a == base else f"{a}."
        doc = {
            "version": 0.1,
            "source": f"{catalog}.{base_t.table.lower()}",
            "comment": sv.description,
            "joins": joins,
            "dimensions": [{"name": title_words(f.name).title(), "expr": f"{prefix(f.alias)}{f.expr}"}
                           for f in sv.dimensions if f.alias in reachable],
            "measures": [],
        }
        for m in sv.metrics:
            if m.alias not in reachable:
                continue
            e = m.expr
            for f in sv.facts:
                e = e.replace(f"{f.alias}.{f.name}", f"{prefix(f.alias)}{f.expr}")
            doc["measures"].append({"name": title_words(m.name).title(), "expr": e})
        skipped = [t.alias for t in sv.tables if t.alias not in reachable]
        text = f"# Databricks Unity Catalog metric view for {sv.name} (generated by SemanticLift {__version__})\n"
        if skipped:
            text += f"# Not reachable from {base} (model as a separate metric view): {', '.join(skipped)}\n"
        out[f"semantic/databricks/{sv.name.lower()}.yaml"] = text + to_yaml(doc)
    return out


# --------------------------------------------------------------------------- dbt
def dbt_project(g: MetaGraph, d: Design, cfg: dict) -> dict[str, str]:
    files = {}
    name = "semlift_" + re.sub(r"[^a-z0-9]+", "_", cfg["target"]["database"].lower())
    files["dbt/dbt_project.yml"] = to_yaml({
        "name": name, "version": __version__, "config-version": 2, "profile": name,
        "model-paths": ["models"], "test-paths": ["tests"],
        "models": {name: {"core": {"+schema": "core", "+materialized": "view"},
                          "agg": {"+schema": "agg", "+materialized": "dynamic_table",
                                  "+target_lag": cfg["target"]["refresh_cadence_lag"]["daily"],
                                  "+snowflake_warehouse": cfg["aggregates"]["warehouse"]}}}})
    sources = defaultdict(set)
    for t in d.tables.values():
        if "." in t.source:
            s, tb = t.source.split(".", 1)
            sources[s].add(tb)
        for us in t.union_sources:
            s, tb = us.split("|")[0].split(".", 1)
            sources[s].add(tb)
    files["dbt/models/sources.yml"] = to_yaml({"version": 2, "sources": [
        {"name": s.lower(), "schema": s, "tables": [{"name": tb.lower(), "identifier": tb} for tb in sorted(tbs)]}
        for s, tbs in sorted(sources.items())]})
    schema_models = []
    for tid, t in sorted(d.tables.items()):
        mname = t.name.lower()
        sel = ",\n    ".join(f"{c.expr} as {c.name.lower()}" for c in t.columns)
        src_schema, src_table = (t.source.split(".", 1) + [""])[:2]
        frm = f"{{{{ source('{src_schema.lower()}', '{src_table.lower()}') }}}} src"
        joins = ""
        for j in t.joins:
            jt = j.table
            if jt.startswith("REF."):
                jt = f"{{{{ ref('{jt.split('.')[1].lower()}') }}}}"
            joins += f"\nleft join {jt} {j.alias}\n    on {j.on}"
        body = f"select{' distinct' if t.distinct else ''}\n    {sel}\nfrom {frm}{joins}"
        if t.union_sources:
            body = "\nunion\n".join(
                f"select src.{us.split('|')[1]} as {t.primary_key[0].lower()}\nfrom {{{{ source('{us.split('|')[0].split('.')[0].lower()}', '{us.split('|')[0].split('.')[1].lower()}') }}}} src"
                for us in t.union_sources)
        files[f"dbt/models/core/{mname}.sql"] = (f"-- {t.comment}\n-- confidence {t.confidence:.2f}{' (STUB)' if t.stub else ''}\n"
                                                 f"{{{{ config(enabled={'false' if t.stub else 'true'}) }}}}\n\n{body}\n")
        cols = []
        for c in t.columns:
            tests = []
            if c.name in t.primary_key:
                tests += ["not_null", "unique"]
            for fk in t.foreign_keys:
                if fk.columns == [c.name]:
                    tests.append({"relationships": {"to": f"ref('{fk.ref_table.split('.')[1].lower()}')",
                                                    "field": fk.ref_columns[0].lower()}})
            col = {"name": c.name.lower(), "description": c.comment}
            if tests:
                col["tests"] = tests
            cols.append(col)
        schema_models.append({"name": mname, "description": t.comment, "columns": cols,
                              "meta": {"semlift_confidence": t.confidence, "domain": t.domain}})
    for aid, a in sorted(d.aggregates.items()):
        ft = d.tables[a.fact_table]
        sel = [f"{al}.{col} as {out.lower()}" for al, col, out in a.group_columns] + [f"{sql} as {out.lower()}" for out, sql, _ in a.measures]
        joins = "".join(f"\njoin {{{{ ref('{tid.split('.')[1].lower()}') }}}} {al} on {on}" for al, tid, on in a.joins)
        files[f"dbt/models/agg/{a.name.lower()}.sql"] = (
            f"{{{{ config(enabled={'false' if a.stub else 'true'}) }}}}\n\nselect\n    " + ",\n    ".join(sel)
            + f"\nfrom {{{{ ref('{ft.name.lower()}') }}}} f{joins}\ngroup by all\n")
    files["dbt/models/schema.yml"] = to_yaml({"version": 2, "models": schema_models})
    exposures = []
    for cid, c in sorted(g.clusters.items()):
        if c.disposition == "Retire":
            continue
        deps = sorted({d.ref_to_column[r][0].split(".")[1].lower() for r in c.items if r in d.ref_to_column})
        exposures.append({"name": snake_lower(c.canonical), "type": "analysis", "label": c.canonical.replace("_", " "),
                          "owner": {"name": cfg["owners"]["report_owner"]},
                          "description": f"Cognos intent cluster {cid}: {len(c.members)} reports ({', '.join(c.members)})",
                          "depends_on": [f"ref('{x}')" for x in deps]})
    files["dbt/models/exposures.yml"] = to_yaml({"version": 2, "exposures": exposures})
    return files


# --------------------------------------------------------------------------- contracts
def contracts(g: MetaGraph, d: Design, cfg: dict) -> dict[str, str]:
    out = {}
    for key, p in sorted(d.products.items()):
        schema = []
        for oid in p.outputs:
            o = d.outputs[oid]
            schema.append({"name": o.name, "physicalName": oid, "physicalType": "secure view",
                           "description": o.comment, "status": "stub" if o.stub else "proposed",
                           "properties": [{"name": c} for c in o.columns]})
        grains = {}
        for tid in p.core_tables:
            t = d.tables[tid]
            if t.kind == "fact":
                grains[t.name] = t.primary_key + [fk.columns[0] for fk in t.foreign_keys if fk.columns]
        clusters = [c for c in g.clusters.values() if c.package == key]
        doc = {
            "apiVersion": "v3.0.0", "kind": "DataContract",
            "id": f"urn:datacontract:{p.slug}", "version": __version__, "status": "proposed",
            "product": p.slug, "name": p.name, "domain": p.domain_code.lower(),
            "owner": p.owner, "steward": p.steward, "classification": p.classification, "retention": p.retention,
            "source_systems": p.source_systems, "data_modules": p.data_modules,
            "outputs": p.semantic_views + p.outputs,
            "grain": grains,
            "freshness_sla": p.freshness_sla,
            "slaProperties": [{"property": "latency", "value": p.freshness_sla}],
            "default_filters": [{"dimension": f["dimension"], "value": f["default"], "cognos_prompt": f["parameter"]}
                                for f in p.default_filters],
            "quality": [_quality_entry(q) for q in p.quality],
            "schema": schema,
            "confidence": p.confidence,
            "replaces_cognos_reports": f"{len(clusters)} clusters ({sum(len(c.members) for c in clusters)} reports)"
            if key != "ENTERPRISE" else "shared conformed dimensions",
        }
        out[f"contracts/{p.slug}.yaml"] = to_yaml(doc)
    return out


def _quality_entry(q: dict) -> dict:
    r = q["rule"]
    if r in ("not_null", "unique"):
        return {r: [f"{q['table']}.{c}" for c in q["columns"]]}
    if r == "referential":
        return {"referential": f"{q['table']}.{','.join(q['columns'])} -> {q['references']}"}
    if r == "accepted_values":
        return {"accepted_values": {f"{q['table']}.{q['columns'][0]}": q["values"]}}
    if r == "freshness":
        return {"freshness": {"max_lag": q["max_lag"]}}
    return q


# --------------------------------------------------------------------------- lineage
def trace_rows(g: MetaGraph, d: Design) -> list[dict]:
    rows = []
    for ri in sorted(g.report_items, key=lambda r: (r.report, r.query, r.name, r.expression)):
        rep = g.reports[ri.report]
        ref = f"{ri.resolved_entity}.{ri.ref_item}" if ri.resolved_entity else ""
        obj = g.item(ri.resolved_entity, ri.ref_item) if ri.resolved_entity else None
        fm_item = f"Business Layer.{ref}" if obj is not None and obj.origin == "FM" else ""
        src_col = ""
        tc = d.ref_to_column.get(ref)
        target_col = f"{tc[0]}.{tc[1]}" if tc else ""
        if tc:
            col = d.tables[tc[0]].col(tc[1])
            src_col = col.source_column if col is not None else ""
        sem = d.ref_to_semantic.get(ref, [])
        rows.append({
            "report": ri.report, "report_folder": rep.folder, "package": rep.package, "disposition": rep.disposition,
            "canonical_report": rep.canonical, "cluster": rep.cluster, "query": ri.query, "report_column": ri.name,
            "cognos_expression": ri.expression, "aggregate_override": ri.aggregate, "fm_item": fm_item,
            "resolution": ri.resolution, "source_column": src_col, "target_column": target_col,
            "semantic_objects": "; ".join(sem), "confidence": getattr(obj, "confidence", ""),
        })
    return rows


def traceability_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()) if rows else ["report"], lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def openlineage(g: MetaGraph, d: Design, cfg: dict) -> str:
    """OpenLineage-style events: RAW -> CORE (column lineage), CORE -> SEM and Cognos report -> SEM."""
    ns = f"snowflake://{cfg['target']['database'].lower()}"
    run_id = stable_hash({"v": __version__, "tables": sorted(d.tables), "sv": sorted(d.semantic_views)}, 32)
    run_id = f"{run_id[:8]}-{run_id[8:12]}-{run_id[12:16]}-{run_id[16:20]}-{run_id[20:32]}"
    producer = f"https://semlift/{__version__}"
    events = []
    for tid, t in sorted(d.tables.items()):
        fields = {}
        inputs = defaultdict(set)
        for c in t.columns:
            srcs = [s.strip() for s in c.source_column.split(",") if s.strip()]
            inp = []
            for s in srcs:
                parts = s.split(".")
                if len(parts) >= 3:
                    ds = ".".join(parts[:-1])
                    inputs[ds].add(parts[-1])
                    inp.append({"namespace": ns, "name": ds, "field": parts[-1]})
            if inp:
                fields[c.name] = {"inputFields": inp, "transformationDescription": c.expr,
                                  "transformationType": "IDENTITY" if c.expr.count(".") == 1 and "(" not in c.expr else "TRANSFORMED"}
        events.append({
            "eventType": "COMPLETE", "eventTime": "1970-01-01T00:00:00Z", "producer": producer,
            "schemaURL": "https://openlineage.io/spec/2-0-2/OpenLineage.json#/definitions/RunEvent",
            "run": {"runId": run_id}, "job": {"namespace": "semlift", "name": f"design.{tid}"},
            "inputs": [{"namespace": ns, "name": k, "facets": {"schema": {"fields": [{"name": c} for c in sorted(v)]}}}
                       for k, v in sorted(inputs.items())],
            "outputs": [{"namespace": ns, "name": tid, "facets": {"columnLineage": {"fields": fields},
                                                                   "documentation": {"description": t.comment}}}],
        })
    for sid, sv in sorted(d.semantic_views.items()):
        reports = sorted({m for cid in sv.clusters for m in g.clusters[cid].members})
        events.append({
            "eventType": "COMPLETE", "eventTime": "1970-01-01T00:00:00Z", "producer": producer,
            "run": {"runId": run_id}, "job": {"namespace": "semlift", "name": f"design.{sid}"},
            "inputs": [{"namespace": ns, "name": t.table} for t in sv.tables]
                      + [{"namespace": "cognos://content-store", "name": r} for r in reports],
            "outputs": [{"namespace": ns, "name": sid}],
        })
    return json.dumps(events, indent=1, sort_keys=False)


# --------------------------------------------------------------------------- findings.md
def findings_md(g: MetaGraph, d: Design) -> str:
    lines = [f"# SemanticLift findings register", "",
             f"Generated by SemanticLift {__version__}. {len(g.findings)} findings.", ""]
    by = defaultdict(list)
    for f in g.findings:
        by[f.code].append(f)
    from ..analyze.findings import CODES
    lines += ["| Code | Finding | Count | Highest severity |", "| --- | --- | --- | --- |"]
    order = {"high": 0, "medium": 1, "low": 2, "info": 3}
    for code in sorted(by, key=lambda c: int(c[1:])):
        fs = by[code]
        sev = min((f.severity for f in fs), key=lambda s: order.get(s, 9))
        lines.append(f"| {code} | {CODES.get(code, fs[0].title)} | {len(fs)} | {sev} |")
    lines.append("")
    for code in sorted(by, key=lambda c: int(c[1:])):
        lines += [f"## {code} - {CODES.get(code, '')}", ""]
        for f in by[code]:
            lines += [f"### {f.id} ({f.severity}{', BLOCKING' if f.blocking else ''}) {f.title}", "",
                      f"- **Object:** {f.object}", f"- **Evidence:** {f.evidence}", f"- **Owner:** {f.owner or '-'}",
                      f"- **Resolution:** {f.resolution or '-'}", f"- **Status:** {f.status}", ""]
    nc = g.analysis.get("numbers_that_change", [])
    if nc:
        lines += ["## Numbers that will change after migration (F6)", "",
                  "| Report | Measure | Cognos | Semantic layer |", "| --- | --- | --- | --- |"]
        lines += [f"| {r['report']} | {r['measure']} | {r['cognos']} | {r['semantic']} |" for r in nc]
        lines.append("")
    v = g.analysis.get("validation", [])
    if v:
        lines += ["## Validation rules (spec 8.3)", "", "| Rule | Check | Result | Detail |", "| --- | --- | --- | --- |"]
        for r in v:
            res = "n/a" if r["passed"] is None else ("PASS" if r["passed"] else "FAIL")
            lines.append(f"| {r['rule']} | {r['title']} | {res} | {r['detail']} |")
        lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- parity SQL
def parity_sql(g: MetaGraph, d: Design, cfg: dict) -> dict[str, str]:
    """FR-14: per sampled report, the Cognos-equivalent SQL (report aggregates as authored) vs the semantic view."""
    files = {}
    tol = cfg["parity"]["tolerance_pct"]
    n = int(cfg["parity"]["sample_reports"])
    live = sorted((c for c in g.clusters.values() if c.disposition != "Retire"),
                  key=lambda c: (-(g.reports[c.canonical].runs_per_day or 0), c.id))
    sv_for_cluster = {cid: sv for sv in d.semantic_views.values() for cid in sv.clusters}
    index = []
    for c in live:
        if len(index) >= n:
            break
        sv = sv_for_cluster.get(c.id)
        if sv is None or sv.stub:
            continue
        q = next((x for x in sv.verified_queries if x.cluster == c.id), None)
        dims = [f for f in sv.dimensions if f.ref in c.items]
        mets = [m for m in sv.metrics if m.ref in c.items]
        if not mets:
            continue
        rep = g.reports[c.canonical]
        items = {f"{ri.resolved_entity}.{ri.ref_item}": ri for ri in g.report_items if ri.report == rep.name}
        # Cognos-equivalent: every measure aggregated the way the report says ('total' -> SUM)
        cognos_metrics, semantic_metrics, changed = [], [], []
        for m in mets:
            meas = g.measures.get(m.ref)
            ri = items.get(m.ref)
            agg_override = (ri.aggregate if ri else "total") or "total"
            cog = {"total": "SUM", "sum": "SUM", "average": "AVG", "maximum": "MAX", "minimum": "MIN"}.get(agg_override, "SUM")
            sem = AGG_SQL.get(meas.default_aggregation if meas else "sum", "SUM") if m.aggregation != "ratio" else "RATIO"
            if sem != cog:
                changed.append(m.name)
            fact = next(f for f in sv.facts if f.ref == m.ref) if any(f.ref == m.ref for f in sv.facts) else None
            if fact is None:
                continue
            cognos_metrics.append(f"{cog}({fact.alias}.{fact.expr}) AS {m.name}")
            semantic_metrics.append(m)
        if not semantic_metrics:
            continue
        alias_table = {t.alias: t.table for t in sv.tables}
        base = semantic_metrics[0].alias
        joins, joined = [], {base}
        from ..design.semantic import join_path
        for x in dims:
            if x.alias in joined:
                continue
            path = join_path(d, alias_table[base], alias_table[x.alias])
            if not path:
                continue
            for frm, to, fc, tc in path:
                ta = next(a for a, t in alias_table.items() if t == to)
                fa = next(a for a, t in alias_table.items() if t == frm)
                if ta in joined:
                    continue
                joins.append(f"JOIN {to} {ta} ON " + " AND ".join(f"{fa}.{p} = {ta}.{q}" for p, q in zip(fc, tc)))
                joined.add(ta)
        dims = [x for x in dims if x.alias in joined]
        dim_cols = [f"{x.alias}.{x.expr} AS {x.name}" for x in dims]
        fy = next((f for f in sv.default_filters if f["parameter"] == "p_FiscalYear"), None)
        where = f"WHERE dt.FISCAL_YEAR = {fy['default']}" if fy and "dt" in joined else ""
        group = f"GROUP BY {', '.join(str(i + 1) for i in range(len(dims)))}" if dims else ""
        cognos_sql = (f"SELECT {', '.join(dim_cols + cognos_metrics)}\nFROM {alias_table[base]} {base}\n" + "\n".join(joins)
                      + (f"\n{where}" if where else "") + (f"\n{group}" if group else ""))
        semantic_sql = (f"SELECT * FROM SEMANTIC_VIEW(\n    {sv.id}\n" + (f"    DIMENSIONS {', '.join(f'{x.alias}.{x.name}' for x in dims)}\n" if dims else "")
                        + f"    METRICS {', '.join(f'{m.alias}.{m.name}' for m in semantic_metrics)}\n)"
                        + (f" WHERE fiscal_year = {fy['default']}" if where else ""))
        keys = [x.name for x in dims]
        on = " AND ".join(f"c.{k} IS NOT DISTINCT FROM s.{k}" for k in keys) or "TRUE"
        checks = ",\n    ".join(
            f"SUM(c.{m.name}) AS cognos_{m.name}, SUM(s.{m.name}) AS semantic_{m.name},\n"
            f"    IFF(ABS(COALESCE(SUM(s.{m.name}), 0) - COALESCE(SUM(c.{m.name}), 0)) <= {tol} / 100 * ABS(NULLIF(SUM(c.{m.name}), 0)), 'PASS', "
            + (f"'EXPECTED_CHANGE (F6)'" if m.name in changed else "'FAIL'") + f") AS status_{m.name}"
            for m in semantic_metrics)
        sql = (f"-- Parity test for Cognos report {rep.name} (cluster {c.id}, {rep.runs_per_day:g} runs/day)\n"
               f"-- Generated by SemanticLift {__version__}; tolerance +/-{tol}% on totals\n"
               + (f"-- Measures whose numbers are expected to change (F6 aggregation correction): {', '.join(changed)}\n" if changed else "")
               + f"WITH cognos AS (\n{_indent(cognos_sql)}\n),\nsemantic AS (\n{_indent(semantic_sql)}\n)\n"
               f"SELECT\n    (SELECT COUNT(*) FROM cognos) AS cognos_rows,\n    (SELECT COUNT(*) FROM semantic) AS semantic_rows,\n    {checks}\n"
               f"FROM cognos c\nFULL OUTER JOIN semantic s ON {on};\n")
        fname = f"validation/parity_{snake_lower(rep.name)}.sql"
        files[fname] = sql
        index.append({"report": rep.name, "cluster": c.id, "semantic_view": sv.id, "file": fname,
                      "runs_per_day": rep.runs_per_day, "expected_changes": changed})
    files["validation/parity_index.json"] = json.dumps(index, indent=2)
    return files


def _indent(s: str, n: int = 4) -> str:
    return "\n".join(" " * n + line for line in s.splitlines())
