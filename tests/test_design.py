def test_fct_billing_matches_spec_sample(result):
    ddl = obj(result, "CORE.FCT_BILLING").ddl
    assert "src.BILL_DATE_KEY" in ddl and "AS DATE_KEY" in ddl
    assert "src.BILL_AMOUNT + src.TAX_AMOUNT" in ddl
    assert "IFF(src.PAYMENT_STATUS = 'Overdue', 'Yes', 'No')" in ddl
    assert "FROM RAW_CCB.BILLING src" in ddl
    assert "WITH MASKING POLICY SEC.MP_RESTRICTED_AMOUNT" in ddl


def test_constant_externalized(result):
    ddl = obj(result, "CORE.FCT_METER_READING").ddl
    assert "0.233" not in ddl.split("AS\nSELECT")[1]
    assert "REF.REF_EMISSION_FACTOR" in ddl and "ref_1.FACTOR_VALUE" in ddl


def test_ratio_metrics_not_stored(result):
    ddl = obj(result, "CORE.FCT_GENERATION").ddl
    assert "CO2_INTENSITY" not in ddl
    sv = obj(result, "SEM.SV_GENERATION_MIX").ddl
    assert "SUM(generation.co2_emissions_kg) / NULLIF(SUM(generation.generated_mwh), 0)" in sv


def test_no_sum_of_non_additive(result):
    v2 = next(v for v in result.graph.analysis["validation"] if v["rule"] == "V2")
    assert v2["passed"], v2["failures"]
    sv = obj(result, "SEM.SV_GENERATION_MIX").ddl
    assert "AVG(generation.capacity_factor_pct)" in sv
    assert "MAX(generation.capacity_mw)" in sv


def test_validation_rules_pass(result):
    for v in result.graph.analysis["validation"]:
        assert v["passed"] in (True, None), v


def test_security_translation(result):
    rap = obj(result, "SEC.RAP_REGION").ddl
    assert "IS_ROLE_IN_SESSION('REPORT_ADMINS')" in rap and "SEC.MAP_USER_REGION" in rap
    assert "WITH ROW ACCESS POLICY SEC.RAP_REGION ON (REGION)" in obj(result, "CORE.DIM_LOCATION").ddl
    mp = obj(result, "SEC.MP_CREDIT_SCORE").ddl
    assert "FINANCE_ANALYSTS" in mp and "CREDIT_RISK_TEAM" in mp
    grants = obj(result, "SEC.MAP_ROLE_GRANT").ddl
    assert "'BILL_AMOUNT', 'BILLING_ANALYSTS', 'ALLOW'" in grants
    assert "'BILL_AMOUNT', 'FIELD_TECHNICIANS', 'DENY'" in grants


def test_stubs_for_inferred(result):
    for oid in ("CORE.FCT_LOAD_FORECAST", "CORE.FCT_BUDGET_ACTUAL", "SEM.SV_NERC_COMPLIANCE"):
        o = obj(result, oid)
        assert o.status == "stub" and o.confidence < 0.6 and "STUB" in o.ddl


def test_every_object_has_governance(result):
    for o in result.objects:
        assert "-- Generated by: SemanticLift" in o.ddl
        assert o.meta["file"].startswith("ddl/")
    orders = [o.order for o in result.objects]
    assert orders == sorted(orders) and len(set(orders)) == len(orders)


def test_dependency_order(result):
    pos = {o.id: o.order for o in result.objects}
    for o in result.objects:
        for dep in o.depends_on:
            if dep in pos:
                assert pos[dep] < o.order, (o.id, dep)


def test_all_sql_parses(result):
    res = check_all(result.objects)
    failed = {k: v for k, v in res.items() if v["status"] == "failed"}
    assert not failed, failed


def test_determinism(result, tmp_path):
    again = run(BUNDLE, tmp_path, ESTATE)
    a = {o.id: o.ddl for o in result.objects}
    b = {o.id: o.ddl for o in again.objects}
    assert a == b


def test_no_statement_hidden_in_comment(result):
    for o in result.objects:
        for line in o.ddl.splitlines():
            if "--" in line:
                assert not re.search(r"--.*;\s*$", line) or line.strip().startswith("--"), (o.id, line)
